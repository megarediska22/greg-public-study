import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { adaptUnit, catalogEntry } from '../src/content/extension/adaptUnit.ts';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const directory = path.join(root, 'src/content/extension');
const units = path.join(directory, 'units');
const generated = path.join(directory, 'generated');
const plan = fs.readFileSync(path.join(root, 'research/curriculum/curriculum-100.md'), 'utf8');
const titles = new Map([...plan.matchAll(/^\| <a id="unit-(\d+)"><\/a>([^|]+)\|/gm)].map(([, n, cell]) => [Number(n), cell.trim().split(' · ').slice(1).filter(part => /[а-яё]/iu.test(part)).join(' · ')]));
const files = fs.existsSync(units) ? fs.readdirSync(units).filter(file => file.endsWith('.json')).sort() : [];
const entries = [];
const loaders = [];
const replayLoaders = [];
fs.mkdirSync(generated, { recursive: true });
function write(name, text) {
  const filename = path.join(generated, name);
  if (!fs.existsSync(filename) || fs.readFileSync(filename, 'utf8') !== text) fs.writeFileSync(filename, text);
}
for (const file of files) {
  if (!/^\d{3}\.json$/.test(file)) throw Error(`Unexpected authored filename: ${file}`);
  const unit = JSON.parse(fs.readFileSync(path.join(units, file), 'utf8'));
  if (file !== `${String(unit.number).padStart(3, '0')}.json`) throw Error(`${file}: filename and number mismatch`);
  const lesson = adaptUnit(unit);
  const title = titles.get(unit.number);
  if (!title) throw Error(`${file}: no approved plan row`);
  // Catalog always uses the real plan title, stripped of anchors/subtitle/level.
  // Preserve the author's data; the adapter uses the same plan title on load.
  const entry = { ...catalogEntry(unit), title };
  entries.push(entry);
  const groups = lesson.steps.filter(step => step.type === 'exercise').map(step => step.questions.map(question => {
    return question.type === 'choice' ? [question.id, question.acceptedAnswers, question.options] : [question.id, question.acceptedAnswers];
  }));
  write(`replay-${entry.id}.ts`, `// Generated by npm run course:refresh. Engine keys only.\nexport default ${JSON.stringify({ id: lesson.id, level: lesson.level, groups })};\n`);
  loaders.push(`  ${JSON.stringify(entry.id)}: () => readUnit('${file}', () => import('../units/${file}')),`);
  replayLoaders.push(`  ${JSON.stringify(entry.id)}: () => import('./replay-${entry.id}.ts').then(module => module.default as unknown as ReplayData),`);
}
write('catalog.ts', `// Generated by npm run course:refresh. No rich unit imports.\nimport type { CourseEntry } from '../../../types/lesson.ts';\nexport const availableEntries: readonly CourseEntry[] = ${JSON.stringify(entries, null, 2)};\n`);
write('loaders.ts', `// Generated by npm run course:refresh. Each import is a separate production chunk.\nimport type { AuthoredUnit, ReplayData } from '../adaptUnit.ts';\n// Vite serves each static JSON import as a JS module. Direct Node tests use native JSON.\nfunction readUnit(file: string, fromVite: () => Promise<{ default: unknown }>): Promise<AuthoredUnit> {\n  const request = import.meta.env?.MODE ? fromVite() : import(/* @vite-ignore */ '../units/' + file, { with: { type: 'json' } });\n  return request.then(module => module.default as AuthoredUnit);\n}\nexport const unitLoaders: Record<string, () => Promise<AuthoredUnit>> = {\n${loaders.join('\n')}\n};\nexport const replayLoaders: Record<string, () => Promise<ReplayData>> = {\n${replayLoaders.join('\n')}\n};\n`);
const current = new Set(entries.map(entry => entry.id));
for (const file of fs.readdirSync(generated)) {
  if (file.startsWith('replay-unit-') && !current.has(file.slice(7, -3))) fs.unlinkSync(path.join(generated, file));
}
let contiguous = 0;
while (current.has(`unit-${String(27 + contiguous).padStart(3, '0')}`)) contiguous++;
console.log(`Extension refreshed: ${entries.length}/95 authored, ${contiguous} contiguous catalog entries; ${entries.length * 15} questions. Raw JSON files unchanged.`);
if (process.argv.includes('--final') && (entries.length !== 95 || contiguous !== 95)) throw Error('Final gate requires exactly units 027–121 (95 authored lessons / 1425 questions), with no gaps.');
